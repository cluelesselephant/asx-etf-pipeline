-- 1. A dedicated role that owns everything the pipeline builds
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS ETF_TRANSFORMER;
GRANT ROLE ETF_TRANSFORMER TO ROLE SYSADMIN;
GRANT CREATE DATABASE ON ACCOUNT TO ROLE ETF_TRANSFORMER;

-- Let your own login use this role (for Snowsight and Power BI)
GRANT ROLE ETF_TRANSFORMER TO USER "thutrang.tran";

-- 2. A small warehouse that suspends after 60 seconds to save credits
CREATE WAREHOUSE IF NOT EXISTS ETF_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
GRANT USAGE ON WAREHOUSE ETF_WH TO ROLE ETF_TRANSFORMER;

-- 3. A service user for the pipeline (key-pair login only, no password)
CREATE USER IF NOT EXISTS ETF_PIPELINE_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = ETF_TRANSFORMER
  DEFAULT_WAREHOUSE = ETF_WH
  COMMENT = 'ASX ETF pipeline service account';
GRANT ROLE ETF_TRANSFORMER TO USER ETF_PIPELINE_SVC;

-- 4. Database and raw schema, owned by the pipeline role
USE ROLE ETF_TRANSFORMER;
CREATE DATABASE IF NOT EXISTS ETF_DB;
CREATE SCHEMA IF NOT EXISTS ETF_DB.RAW;
USE SCHEMA ETF_DB.RAW;

CREATE TABLE IF NOT EXISTS ETF_PRICES (
  TICKER VARCHAR, PRICE_DATE DATE,
  OPEN FLOAT, HIGH FLOAT, LOW FLOAT, CLOSE FLOAT, ADJ_CLOSE FLOAT,
  VOLUME NUMBER, SOURCE VARCHAR, LOADED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS FUND_METADATA (
  TICKER VARCHAR, FUND_NAME VARCHAR, ISSUER VARCHAR, ASSET_CLASS VARCHAR,
  REGION VARCHAR, MGMT_FEE_PCT FLOAT, INCEPTION_DATE DATE,
  SOURCE_FILE VARCHAR, LOADED_AT TIMESTAMP_NTZ
);

-- Every pipeline run writes one row here
CREATE TABLE IF NOT EXISTS LOAD_AUDIT (
  RUN_ID VARCHAR, SOURCE VARCHAR, ROWS_LOADED NUMBER,
  STATUS VARCHAR, MESSAGE VARCHAR, RUN_AT TIMESTAMP_NTZ
);